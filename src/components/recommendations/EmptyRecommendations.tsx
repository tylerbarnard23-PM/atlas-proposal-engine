import Link from "next/link";
import { Bot, ClipboardList, Plus } from "lucide-react";
import { Button } from "@/components/ui/Button";
import { analysisRun, useCopilotMode } from "@/components/copilot/CopilotWorkspace";

// #111: the workspace starts with no recommendations. The empty list says how
// recommendations arrive, in words that match what Stratovell AI actually runs
// here. An empty list says nothing about whether an analysis has run: a
// preview that wasn't added leaves no record.

export const EMPTY_RECOMMENDATIONS_TITLE = "No recommendations added yet.";

/** The empty state's explanation for the server's actual mode (null while it isn't known). */
export function emptyRecommendationsCopy(run: ReturnType<typeof analysisRun>): string {
  const steps =
    "Recommendations appear here only when you add them. Review the client objectives, run an analysis in Stratovell AI, inspect its draft previews and add the drafts you select; adding never approves anything. You can also write your own recommendation.";
  if (!run) return steps;
  // #113: the hosted site, before this user has signed in and connected their own key.
  if (run.hostedSignIn)
    return `${steps} On this site, Claude runs only after you sign in and connect your own Anthropic API key; until then Stratovell AI runs a labelled scripted example, not Claude.`;
  if (run.runAs === "scripted_example")
    return `${steps} On this hosted demo, Stratovell AI runs a scripted example, not Claude: its drafts are labelled as examples, not an analysis of this client.`;
  if (run.runAs === "test_provider") return `${steps} This server answers with the test provider, not Claude: its drafts are labelled as test examples.`;
  return `${steps} With Claude connected, Claude analyzes the client brief and the portfolio, and its drafts stay previews until you add them.`;
}

export function EmptyRecommendations({ onWrite }: { onWrite: () => void }) {
  const mode = useCopilotMode();
  return (
    <div className="border border-dashed border-ink-200 rounded-lg p-8 text-center bg-slatey-50/50" data-testid="recommendations-empty">
      <h4 className="text-sm font-semibold text-ink-900">{EMPTY_RECOMMENDATIONS_TITLE}</h4>
      <p className="text-sm text-ink-600 mt-1 max-w-xl mx-auto" data-testid="recommendations-empty-text">
        {emptyRecommendationsCopy(analysisRun(mode))}
      </p>
      <div className="mt-4 flex flex-wrap gap-2 justify-center">
        <Link href="/client-objectives">
          <Button variant="secondary" iconLeft={<ClipboardList className="h-4 w-4" />}>
            Review client objectives
          </Button>
        </Link>
        <Link href="/copilot">
          <Button variant="secondary" iconLeft={<Bot className="h-4 w-4" />}>
            Open Stratovell AI
          </Button>
        </Link>
        <Button onClick={onWrite} iconLeft={<Plus className="h-4 w-4" />}>
          Write a recommendation
        </Button>
      </div>
    </div>
  );
}

/** #111: shown above the list whenever prewritten samples are present. */
