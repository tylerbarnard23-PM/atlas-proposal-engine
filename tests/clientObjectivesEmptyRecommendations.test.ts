describe("existing records are kept and clarified", () => {
  it("a saved workspace with samples, edits, approvals, alternatives and a version reloads unchanged (no migration)", async () => {
    let m = await load();
    loadSampleRecommendations(m.useAtlasStore);
    const [first, second] = store(m).recommendations;
    store(m).upsertRecommendation({ ...first, title: `${first.title} (edited, synthetic)` });
    store(m).upsertRecommendation({ ...store(m).recommendations.find((r) => r.id === second.id)!, approvedByAdvisor: true, status: "approved", includeInPdf: true });
    store(m).setDraftMember(second.id, true);
    store(m).duplicateDraft("Copy (synthetic)");
    const before = JSON.parse(JSON.stringify({ recs: store(m).recommendations, alternatives: store(m).alternatives, draft: store(m).workingDraft, snapshots: store(m).snapshots }));
    expect(before.alternatives).toHaveLength(1);

    vi.resetModules(); // a reload: the store hydrates from the saved key
    m = await load();
    const s = store(m);
    expect(JSON.parse(JSON.stringify({ recs: s.recommendations, alternatives: s.alternatives, draft: s.workingDraft, snapshots: s.snapshots }))).toEqual(before);
    expect(s.recommendations.filter((r) => m.isPrewrittenSample(r)).length).toBe(7); // six samples and the copy of the draft's one member
    expect(m.originLabel(s.recommendations.find((r) => r.id === first.id)!).label).toBe("Sample example (prewritten), edited by advisor");
  });

  it("a backup carrying the prewritten samples restores every record, origin and approval", async () => {
    const m = await load();
    loadSampleRecommendations(m.useAtlasStore);
    const id = store(m).recommendations[0].id;
    store(m).upsertRecommendation({ ...store(m).recommendations[0], approvedByAdvisor: true, status: "approved", includeInPdf: true });
    const ids = { disclosureIds: m.DISCLOSURE_LIBRARY.map((d) => d.id) };
    const exported = m.exportBackup(store(m), NOW, ids);
    if (!exported.ok) throw new Error(exported.errors.join("; "));
    const before = store(m).recommendations;
    store(m).resetSeed();
    expect(store(m).recommendations).toEqual([]);
    const parsed = m.parseBackup(exported.text, ids);
    if (!parsed.ok) throw new Error(parsed.errors.join("; "));
    const r = store(m).restoreWorkspace(m.restoredState(parsed.backup, { advisor: store(m).advisor, disclosures: m.DISCLOSURE_LIBRARY }, { replaceFirm: false }));
    expect(r).toEqual({ ok: true });
    expect(store(m).recommendations).toEqual(before);
    expect(store(m).recommendations.find((x) => x.id === id)!.approvedByAdvisor).toBe(true);
    expect(store(m).recommendations.map((x) => m.originLabel(x).label)).toEqual(before.map((x) => m.originLabel(x).label));
  });

  it("per-record origins stay accurate: editing, copying or approving never turns an example into Claude's analysis", async () => {
    const m = await load();
    loadSampleRecommendations(m.useAtlasStore);
    const seed = store(m).recommendations[0];
    const base = { ...seed, origin: undefined } as Recommendation;
    const records: [Recommendation, string, boolean][] = [
      [{ ...base, id: "rec_claude_s", origin: { kind: "claude", models: ["claude-opus-5-5"] } }, "Claude draft", false],
      [{ ...base, id: "rec_advisor_s", origin: { kind: "advisor" } }, "Advisor-authored", false],
      [{ ...base, id: "rec_script_s", origin: { kind: "example", source: "scripted_demo" } }, "Scripted example (not Claude)", false],
      [{ ...base, id: "rec_test_s", origin: { kind: "example", source: "test_provider" } }, "Test provider example (not a model)", false],
      [{ ...base, id: "rec_unknown_s" }, "Origin not recorded", false],
    ];
    m.useAtlasStore.setState({ recommendations: [...store(m).recommendations, ...records.map((x) => x[0])] });
    for (const [r, label, sample] of records) {
      expect(m.originLabel(r).label, r.id).toBe(label);
      expect(m.isPrewrittenSample(r), r.id).toBe(sample);
    }
    expect(m.originLabel(seed).label).toBe("Sample example (prewritten)");
    expect(m.isPrewrittenSample(seed)).toBe(true);

    // Edit, approve and copy every record: each keeps where it came from, and only Claude's record says Claude.
    // An unknown origin stays unknown ("unrecorded") after an edit; nothing is inferred.
    const known = (r: Recommendation) => m.knownOrigin(r) ?? { kind: "unrecorded" as const };
    const kindBefore = new Map(store(m).recommendations.map((r) => [r.id, known(r)] as const));
    for (const r of [...store(m).recommendations]) {
      store(m).upsertRecommendation({ ...r, rationale: `${r.rationale} (edited, synthetic)` });
      store(m).upsertRecommendation({ ...store(m).recommendations.find((x) => x.id === r.id)!, approvedByAdvisor: true, status: "approved", includeInPdf: true });
      store(m).setDraftMember(r.id, true);
    }
    store(m).duplicateDraft("Copy (synthetic)");
    const s = store(m);
    for (const [id, before] of kindBefore) {
      const after = known(s.recommendations.find((r) => r.id === id)!);
      expect(after.kind, id).toBe(before.kind);
      expect("source" in after ? after.source : null, id).toBe("source" in before ? before.source : null);
    }
    const claudeLabelled = s.recommendations.filter((r) => /^Claude draft/.test(m.originLabel(r).label));
    expect(claudeLabelled.map((r) => r.origin?.kind)).toEqual(["claude", "claude"]); // the Claude record and its copy
    expect(s.recommendations.filter((r) => m.isPrewrittenSample(r)).length).toBe(12); // six samples and six copies
  });
});

